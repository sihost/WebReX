#!/usr/bin/env python3
"""WP2 step 1: SDK fixed SPIR-V shaders -> WGSL headers (build-time conversion).

  python gen_fixed_wgsl.py [--sdk <repo root>] [--rex out/tint-host/rex_spirv_to_wgsl]

Reads src/graphics/shaders/vulkan_spirv/<name>.h (generated by `xb buildshaders`), converts
each module with rex_spirv_to_wgsl --texel-buffers-as-1d (the same SpirvToWgsl() the wasm64
build links; the output is re-validated by Tint's WGSL resolver) and writes
src/graphics/shaders/webgpu_wgsl/<name>.h with `const char <name>_wgsl[]`, plus a comment
listing the resource bindings the host has to provide. Rewrites relative to the Vulkan
shader: push constants are a uniform buffer in the group after the shader's own sets,
texel buffers are texture_1d / texture_storage_1d (fetched at LOD 0).
Fails (exit 1) if any shader does not convert, so it can run as a build step.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run_corpus import extract_fixed  # noqa: E402

BINDING_RE = re.compile(r"^@group\((\d+)u?\) @binding\((\d+)u?\) var(<[^>]*>)? (\w+) : ([^;]+);",
                        re.M)


def c_string_lines(text):
    out = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{esc}\\n"')
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", default=os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")))
    ap.add_argument("--rex", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "out", "tint-host", "rex_spirv_to_wgsl" + (".exe" if os.name == "nt" else "")))
    a = ap.parse_args()
    src_dir = os.path.join(a.sdk, "src", "graphics", "shaders", "vulkan_spirv")
    dst_dir = os.path.join(a.sdk, "src", "graphics", "shaders", "webgpu_wgsl")
    os.makedirs(dst_dir, exist_ok=True)
    failed = 0
    with tempfile.TemporaryDirectory() as tmp:
        spvs = extract_fixed(src_dir, tmp)
        for spv in spvs:
            name = os.path.splitext(os.path.basename(spv))[0]
            wgsl_path = os.path.join(tmp, name + ".wgsl")
            p = subprocess.run([a.rex, "--texel-buffers-as-1d", spv, wgsl_path],
                               capture_output=True, text=True)
            if p.returncode != 0:
                print(f"FAILED {name}: {p.stderr.strip()}", file=sys.stderr)
                failed += 1
                continue
            wgsl = open(wgsl_path, encoding="utf-8").read().rstrip("\n")
            bindings = BINDING_RE.findall(wgsl)
            lines = [
                "// Generated by scripts/gen_fixed_wgsl.py from",
                f"// ../vulkan_spirv/{name}.h with SpirvToWgsl (Tint, Dawn 31e25af2). Do not edit.",
                "//",
                "// Bindings:",
            ]
            for g, b, space, var, ty in bindings:
                lines.append(f"//   @group({g}) @binding({b}) {var}: {space}{ty.strip()}")
            lines += ["", "#pragma once", "", f"const char {name}_wgsl[] =",
                      c_string_lines(wgsl) + ";", ""]
            out = os.path.join(dst_dir, name + ".h")
            with open(out, "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(lines))
    print(f"{len(spvs) - failed}/{len(spvs)} fixed shaders -> {dst_dir}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
