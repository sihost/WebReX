#!/usr/bin/env python3
"""Generate cmake/ffmpeg_wasm/config.h for the Emscripten (wasm64) build.

FFmpeg's ./configure cannot run on this Windows host for an Emscripten target,
and the vendored submodule only ships x86_64/aarch64 configs. The SDK builds a
fixed source list (wmapro / xmaframes decoder + libavutil), so the config is
derived from config_linux_x86_64.h by turning off every x86 / inline-asm /
Linux-only feature. Re-run after bumping the FFmpeg submodule:

    python cmake/ffmpeg_wasm/gen_config.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "thirdparty", "FFmpeg", "config_linux_x86_64.h")
DST = os.path.join(HERE, "config.h")

X86_EXTS = ["AESNI", "AMD3DNOW", "AMD3DNOWEXT", "AVX", "AVX2", "AVX512", "FMA3", "FMA4",
            "MMX", "MMXEXT", "SSE", "SSE2", "SSE3", "SSE4", "SSE42", "SSSE3", "XOP",
            "CPUNOP", "I686"]

OFF = set(["ARCH_X86", "ARCH_X86_32", "ARCH_X86_64",
           "HAVE_INLINE_ASM", "HAVE_X86ASM", "HAVE_MM_EMPTY", "HAVE_FAST_CMOV",
           "HAVE_EBP_AVAILABLE", "HAVE_EBX_AVAILABLE", "HAVE_XMM_CLOBBERS",
           "HAVE_INLINE_ASM_DIRECT_SYMBOL_REFS", "HAVE_INLINE_ASM_LABELS",
           "HAVE_INLINE_ASM_NONLOCAL_LABELS", "HAVE_SYMVER",
           "HAVE_SIMD_ALIGN_32", "HAVE_SIMD_ALIGN_64", "HAVE_FAST_UNALIGNED",
           # Linux-only headers / syscalls not in the Emscripten sysroot
           "HAVE_ASM_TYPES_H", "HAVE_LINUX_PERF_EVENT_H", "HAVE_SCHED_GETAFFINITY",
           "HAVE_TERMIOS_H", "HAVE_MMAP", "HAVE_PRCTL", "HAVE_GETAUXVAL",
           "HAVE_SYSCTL", "HAVE_SYS_RESOURCE_H", "HAVE_GETRUSAGE",
           "CONFIG_LINUX_PERF"])
for e in X86_EXTS:
    OFF.update(["HAVE_" + e, "HAVE_" + e + "_EXTERNAL", "HAVE_" + e + "_INLINE"])

define_re = re.compile(r"^#define (\w+) (\S.*)$")
out = []
seen = set()
with open(SRC, newline="") as f:
    for line in f.read().splitlines():
        m = define_re.match(line)
        if m:
            name = m.group(1)
            if name in OFF:
                line = "#define %s 0" % name
                seen.add(name)
            elif name == "OS_NAME":
                line = "#define OS_NAME emscripten"
            elif name == "FFMPEG_CONFIGURATION":
                line = ('#define FFMPEG_CONFIGURATION "derived from config_linux_x86_64.h by '
                        'cmake/ffmpeg_wasm/gen_config.py: --arch=wasm64 --disable-asm '
                        '--enable-decoder=xmaframes,wmapro"')
            elif name == "CC_IDENT":
                line = '#define CC_IDENT "emscripten"'
        out.append(line)

header = ["/* GENERATED by cmake/ffmpeg_wasm/gen_config.py - do not edit by hand. */",
          "#if !defined(__EMSCRIPTEN__)",
          '#error "cmake/ffmpeg_wasm/config.h is only for Emscripten builds"',
          "#endif"]
with open(DST, "w", newline="\n") as f:
    f.write("\n".join(header + out) + "\n")
missing = sorted(OFF - seen)
print("wrote", DST, "; overrides not present in source:", missing)
